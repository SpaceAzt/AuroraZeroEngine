#pragma once

/******************************************************************************
 * Aurora Engine
 *
 * File:
 *      LogMessage.h
 *
 * Description:
 *      Represents a single log message.
 ******************************************************************************/

#include "LogLevel.h"

#include <chrono>
#include <string>
#include <thread>

struct LogMessage {
	// -------------------------------------------------------------------------
	// Message
	// -------------------------------------------------------------------------

	LogLevel level = LogLevel::Info;

	std::string message;

	// -------------------------------------------------------------------------
	// Source
	// -------------------------------------------------------------------------

	std::string module;

	// -------------------------------------------------------------------------
	// Time
	// -------------------------------------------------------------------------

	std::chrono::system_clock::time_point timestamp =
			std::chrono::system_clock::now();

	// -------------------------------------------------------------------------
	// Thread
	// -------------------------------------------------------------------------

	std::thread::id threadId =
			std::this_thread::get_id();
};
