#pragma once

/******************************************************************************
 * Aurora Engine
 *
 * File:
 *      ILogger.h
 *
 * Description:
 *      Base interface for all logger implementations.
 ******************************************************************************/

#include "LogMessage.h"

class ILogger {
public:
	// -------------------------------------------------------------------------
	// Lifetime
	// -------------------------------------------------------------------------

	virtual ~ILogger() = default;

	// -------------------------------------------------------------------------
	// Logging
	// -------------------------------------------------------------------------

	virtual void Log(
			const LogMessage &message) = 0;

	// -------------------------------------------------------------------------
	// State
	// -------------------------------------------------------------------------

	[[nodiscard]]
	virtual bool IsEnabled() const = 0;

	virtual void SetEnabled(
			bool enabled) = 0;
};
