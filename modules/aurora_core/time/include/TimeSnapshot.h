#include "TimeTypes.h"

struct TimeSnapshot {
	// -------------------------------------------------------------------------
	// Frame
	// -------------------------------------------------------------------------

	FrameIndex frameIndex = 0;

	// -------------------------------------------------------------------------
	// Time
	// -------------------------------------------------------------------------

	TimeSeconds deltaTime = 0.0;

	TimeSeconds totalTime = 0.0;

	// -------------------------------------------------------------------------
	// Simulation
	// -------------------------------------------------------------------------

	TimeSeconds unscaledDeltaTime = 0.0;

	TimeSeconds fixedDeltaTime = 1.0 / 60.0;

	TimeSeconds timeScale = 1.0;

	// -------------------------------------------------------------------------
	// Statistics
	// -------------------------------------------------------------------------

	double fps = 0.0;
};
